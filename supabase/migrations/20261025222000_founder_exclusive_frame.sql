-- Keep the existing frame validator for the five earned ones.
-- The exclusive founder frame has no automatic achievement path.
CREATE OR REPLACE FUNCTION public.has_player_frame(p_user_id uuid,p_frame_id text)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $frameguard$
DECLARE needed int; score int;
BEGIN
 IF (SELECT auth.uid()) IS NULL OR p_user_id IS NULL THEN RETURN false; END IF;
 IF p_frame_id IS NULL THEN RETURN true; END IF;
 IF p_user_id<>(SELECT auth.uid()) THEN RETURN false; END IF;
 IF p_frame_id='fundador' THEN
  RETURN EXISTS(SELECT 1 FROM public.player_frame_grants g
    WHERE g.user_id=p_user_id AND g.frame_id='fundador');
 END IF;
 IF p_frame_id NOT IN ('safira','dupla-coroa','rei-sequencia','high-roller','conclave')
 THEN RETURN false; END IF;
 IF EXISTS(SELECT 1 FROM public.player_frame_grants g
           WHERE g.user_id=p_user_id AND g.frame_id=p_frame_id) THEN RETURN true; END IF;
 needed=CASE p_frame_id WHEN 'safira' THEN 5 WHEN 'dupla-coroa' THEN 1
  WHEN 'rei-sequencia' THEN 6 WHEN 'high-roller' THEN 5 WHEN 'conclave' THEN 3 END;
 score=coalesce((public.get_player_frame_progress(p_user_id)->>p_frame_id)::int,0);
 RETURN score>=needed;
END; $frameguard$;
REVOKE ALL ON FUNCTION public.has_player_frame(uuid,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.has_player_frame(uuid,text) TO authenticated;

