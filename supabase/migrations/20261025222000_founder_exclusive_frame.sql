-- Only the original general administrator may grant/revoke a founder badge.
-- This is never available through a normal table insert or achievement.
CREATE OR REPLACE FUNCTION public.admin_manage_founder_frame(
 p_user_id uuid,p_action text
) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER
 SET search_path='' AS $founderrpc$
DECLARE actor uuid;
BEGIN
 actor=(SELECT auth.uid());
 IF actor IS NULL OR actor IS DISTINCT FROM
   (SELECT a.user_id FROM public.app_admins a ORDER BY a.created_at,a.user_id LIMIT 1)
 THEN RAISE EXCEPTION 'Apenas o administrador principal pode conceder a moldura Fundador'; END IF;
 IF p_action NOT IN('grant','revoke') OR p_action IS NULL
 THEN RAISE EXCEPTION 'Ação inválida'; END IF;
 IF p_user_id IS NULL OR NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=p_user_id)
 THEN RAISE EXCEPTION 'Jogador inexistente'; END IF;
 IF p_action='grant' THEN
  INSERT INTO public.player_frame_grants(user_id,frame_id,granted_by,reason)
  VALUES(p_user_id,'fundador',actor,'Reconhecimento manual como fundador do Mesa Marcada')
  ON CONFLICT(user_id,frame_id) DO NOTHING;
 ELSE
  DELETE FROM public.player_frame_grants
   WHERE user_id=p_user_id AND frame_id='fundador';
  UPDATE public.profile_frame_showcase
   SET frame_id=NULL,variant='original',updated_at=now()
   WHERE user_id=p_user_id AND frame_id='fundador';
 END IF;
 INSERT INTO public.founder_frame_audit(target_user_id,action,performed_by)
 VALUES(p_user_id,p_action,actor);
 RETURN true;
END; $founderrpc$;
REVOKE ALL ON FUNCTION public.admin_manage_founder_frame(uuid,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.admin_manage_founder_frame(uuid,text) TO authenticated;

